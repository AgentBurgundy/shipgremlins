import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const root = fileURLToPath(new URL("../", import.meta.url));
const output = new URL("../dashboard/motion.js", import.meta.url);
const licenses = await Promise.all(
  ["motion", "framer-motion"].map((name) =>
    readFile(
      new URL(`../node_modules/${name}/LICENSE.md`, import.meta.url),
      "utf8",
    ),
  ),
);
const bundled = await build({
  absWorkingDir: root,
  entryPoints: ["dashboard-src/motion.mjs"],
  bundle: true,
  write: false,
  platform: "browser",
  format: "iife",
  target: ["es2022"],
  minify: true,
  legalComments: "inline",
  define: { "process.env.NODE_ENV": '"production"' },
  banner: {
    js: `// Generated by npm run build:dashboard. Edit dashboard-src/motion*.mjs instead.\n/*! Bundled Motion / Framer Motion and motion-dom / motion-utils licenses:\n${licenses.join("\n").replaceAll("\r\n", "\n")}\n*/`,
  },
});
const generated = await format(bundled.outputFiles[0].text, {
  parser: "babel",
  endOfLine: "lf",
});
if (process.argv.includes("--check")) {
  const existing = await readFile(output, "utf8").catch(() => "");
  if (existing.replaceAll("\r\n", "\n") !== generated) {
    console.error(
      "Dashboard Motion bundle is stale. Run npm run build:dashboard.",
    );
    process.exitCode = 1;
  }
} else {
  await writeFile(output, generated, "utf8");
  console.log(
    "Built dashboard/motion.js from the locally bundled Motion engine.",
  );
}
